using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Nivaes.Serializer.SourceGenerator;

[Generator(LanguageNames.CSharp)]
public sealed class RegisterInterceptorGenerator : IIncrementalGenerator
{
    private sealed class InterceptInfo
    {
        public int Version { get; }
        public string LocationData { get; }
        public string ModelType { get; }
        public string SerializerType { get; }
        public string DeserializerType { get; }
        public uint IdClass { get; }

        public InterceptInfo(
            int version,
            string locationData,
            string modelType,
            string serializerType,
            string deserializerType,
            uint idClass)
        {
            Version = version;
            LocationData = locationData;
            ModelType = modelType;
            SerializerType = serializerType;
            DeserializerType = deserializerType;
            IdClass = idClass;
        }
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var registrations = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) =>
                    node is InvocationExpressionSyntax
                    {
                        Expression: MemberAccessExpressionSyntax
                        {
                            Name.Identifier.ValueText: "Register"
                        }
                    },
                transform: static (ctx, cancellationToken) =>
                {
                    var invocation = (InvocationExpressionSyntax)ctx.Node;

                    if (ctx.SemanticModel.GetSymbolInfo(
                            invocation,
                            cancellationToken).Symbol is not IMethodSymbol method)
                    {
                        return null;
                    }

                    if (method.Name != "Register" ||
                        method.ContainingType.ToDisplayString() !=
                        "Nivaes.Serializer.SerializerModel" ||
                        method.Arity != 1 ||
                        method.TypeArguments[0] is not INamedTypeSymbol model)
                    {
                        return null;
                    }

                    var location = ctx.SemanticModel.GetInterceptableLocation(
                        invocation,
                        cancellationToken);

                    if (location is null)
                        return null;

                    var modelType = model.ToDisplayString(
                        SymbolDisplayFormat.FullyQualifiedFormat);

                    var serializerName =
                        SourceGenerationHelper.GetSerializerClassName(model);

                    var deserializerName =
                        SourceGenerationHelper.GetDeserializerClassName(model);

                    var idClass =
                        SourceGenerationHelper.GetIdClass(model);

                    return new InterceptInfo(
                        location.Version,
                        location.Data,
                        modelType,
                        GetQualifiedTypeName(model, serializerName),
                        GetQualifiedTypeName(model, deserializerName),
                        idClass);
                })
            .Where(static registration => registration is not null)
            .Collect();

        context.RegisterSourceOutput(registrations, static (productionContext, items) =>
        {
            var source = new StringBuilder();

            source.AppendLine("// <auto-generated/>");
            source.AppendLine("#nullable enable");
            source.AppendLine(InterceptsLocationAttributeSource);
            source.AppendLine();
            source.AppendLine("namespace Nivaes.Serializer.SourceGenerator");
            source.AppendLine("{");
            source.AppendLine("    internal static class RegisterInterceptors");
            source.AppendLine("    {");

            var index = 0;

            foreach (var item in items)
            {
                if (item is null)
                    continue;

                var locationData = SymbolDisplay.FormatLiteral(
                    item.LocationData,
                    quote: true);

                source.AppendLine(
                    $"        [global::System.Runtime.CompilerServices.InterceptsLocation({item.Version}, {locationData})]");
                source.AppendLine(
                    $"        internal static void Register_{index}()");
                source.AppendLine("        {");
                source.AppendLine(
                    $"            global::Nivaes.Serializer.SerializerModel.Register<{item.ModelType}, {item.SerializerType}, {item.DeserializerType}>({item.IdClass}u);");
                source.AppendLine("        }");
                source.AppendLine();

                index++;
            }

            source.AppendLine("    }");
            source.AppendLine("}");

            productionContext.AddSource(
                "RegisterInterceptors.g.cs",
                source.ToString());
        });
    }

    private static string GetQualifiedTypeName(
        INamedTypeSymbol model,
        string typeName)
    {
        var containingNamespace = model.ContainingNamespace;

        return containingNamespace.IsGlobalNamespace
            ? $"global::{typeName}"
            : $"global::{containingNamespace.ToDisplayString()}.{typeName}";
    }

    private const string InterceptsLocationAttributeSource =
        """
        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Method,
                AllowMultiple = true)]
            file sealed class InterceptsLocationAttribute
                : global::System.Attribute
            {
                public InterceptsLocationAttribute(int version, string data)
                {
                }
            }
        }
        """;
}